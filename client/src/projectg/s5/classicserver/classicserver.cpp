		// 983 (00b30560 / 00b30570): bits 0 (classico) e 1 ("shortgame") do byte +0xc9 do sRoomInfo (CSharedDoc +0x108f4; roomFlags983 no
		// nosso). No 983 sao thiscall; aqui livres (fastcall, mesmo registro). Nomes meus.
		int IsClassicRoom983(const sRoomInfo* room)
		{
			return *((const unsigned char*)room + 0xc9) & 1;
		}

		int IsShortGameRoom983(const sRoomInfo* room)
		{
			return (*(const unsigned long*)((const char*)room + 0xc9) >> 1) & 1;
		}

