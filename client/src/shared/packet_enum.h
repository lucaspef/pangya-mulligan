//client -> login
enum ClientPacketLoginEnum : unsigned short {
    /// <summary>
           /// ENVIA AO CONECTAR AO SERVIDOR, PARA O MESMO SABER QUE O CLIENTE ESTÁ CONECTADO
           /// </summary>
    CLIENT_REQ_CONNECTED = 0x00,
    /// <summary>
    /// Player digita o usuário e senha e clica em login
    /// </summary>
    CLIENT_REQ_LOGIN = 0x01,
    /// <summary>
    /// Player Seleciona um Servidor Para entrar
    /// </summary>
    CLIENT_REQ_ENTER_SERVER = 0x03,
    /// <summary>
    /// login Com duplicidade 
    /// </summary>
    CLIENT_REQ_KICK = 0x04,
    /// <summary>
    /// Seta primeiro nickname Do usuário
    /// </summary>
    CLIENT_REQ_SET_NICK = 0x06,//SEQUENCIA[0] 
    /// <summary>
    /// Ocorre quando o cliente clica em Confirmar (se o nickname está disponível), 
    /// </summary>
    CLIENT_REQ_CONFIRM_SET_NICK = 0x07,//SEQUENCIA[1] 
    /// <summary>
    /// Player selecionou seu primeiro personagem
    /// </summary>
    CLIENT_REQ_SET_CHARACTER = 0x08,//SEQUENCIA[2] 
    /// <summary>
    /// envia chave De autenficação Do login e lista novamente os servers
    /// </summary>
    CLIENT_REQ_RECONNECT = 0x0B,
    /// <summary>
    /// naosei
    /// </summary>
    CLIENT_REQ_NOTHING = 0xFF
};
